"""MonClub release signing (updater v2, design.md section 5).

Every installer the Access / TV client may install is described by a signed manifest:
ASCII-only JSON, keys sorted, no whitespace, signed with Ed25519 by a key whose PUBLIC half
is embedded in the client (shared/release_keys.py PROD_KEYS) and in the backend config.

Commands
  keygen       --key-id ID          new private key -> %USERPROFILE%\\.monclub\\release-signing\\ID.key
                                    (refuses to overwrite; prints only the PUBLIC key)
  check-trust                       exit 1 unless shared/release_keys.py PROD_KEYS is a non-empty
                                    list of well-formed keys with no "test-" key id (publishable build)
  sign         ...                  hash the installer, build + sign the manifest, write the release
                                    file (section 5.3) -- also for a rollback manifest (--rollback-from)
  verify       --release-file F     check the signature (and, with --installer, hash/size/name)
  check-key    --key-id ID          the private key file matches the trusted public key (pre-build)
  prod-key-ids                      list PROD_KEYS key ids
  public-key   --key-file F         print the public key of a private key file
  tag          --target --channel --version   print the GitHub tag the release uses

The private key file holds the 32-byte Ed25519 seed as 64 lowercase hex chars + "\\n". It is
generated by the OWNER on the build PC, never committed, never printed (design 5.1).
The test key (key id "test-l2-2026-10") lives in tests/fixtures/release_signing/ and is not
secret: it is trusted only by test / E2E builds, which build_release.ps1 marks non-publishable.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import os
import re
import sys
from pathlib import Path
from typing import Any, Mapping

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

try:  # lane L3 owns the one implementation (design 5.1)
    from shared import ed25519 as _ed  # type: ignore[attr-defined]
    ED25519_SOURCE = "shared.ed25519"
except ImportError:  # until L3 lands -- see tools/_ed25519_fallback.py
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import _ed25519_fallback as _ed  # type: ignore[no-redef]
    ED25519_SOURCE = "tools/_ed25519_fallback.py"

MANIFEST_SCHEMA = 1
TARGETS = ("access", "tv")
CHANNELS = ("stable", "beta")
PLATFORM = "WINDOWS"
DEFAULT_GITHUB_REPO = "BOUROUIS-MOHAMED/monclub_access_python"
TEST_KEY_PREFIX = "test-"
TEST_KEY_ID = "test-l2-2026-10"
TEST_KEY_FILE = REPO / "tests" / "fixtures" / "release_signing" / f"{TEST_KEY_ID}.seed"

_VERSION_RE = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z]+(\.[0-9A-Za-z]+)*)?$")
_KEY_ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{2,63}$")
_HEX64_RE = re.compile(r"^[0-9a-f]{64}$")
_HEX128_RE = re.compile(r"^[0-9a-f]{128}$")
_INSTALLER_NAME_RE = re.compile(r"^[A-Za-z0-9._-]{1,128}\.exe$")
_ISSUED_AT_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$")


class ReleaseSignError(Exception):
    """A refusal with a message meant for the person running the build."""


# ------------------------------------------------------------------ naming (one place)


def release_tag(target: str, channel: str, version: str) -> str:
    """The GitHub release tag. publish_github_release.ps1 reads it from the release file."""
    return f"{target}-win-{channel}-v{version}"


def github_asset_url(repo: str, tag: str, asset_name: str) -> str:
    return f"https://github.com/{repo}/releases/download/{tag}/{asset_name}"


def release_file_name(target: str, version: str, *, rollback_from: str | None = None) -> str:
    if rollback_from:
        return f"release-{target}-{version}-rollback-from-{rollback_from}.json"
    return f"release-{target}-{version}.json"


# ------------------------------------------------------------------ keys


def default_key_dir() -> Path:
    home = os.environ.get("USERPROFILE") or str(Path.home())
    return Path(home) / ".monclub" / "release-signing"


def read_seed(path: Path) -> bytes:
    text = Path(path).read_text(encoding="ascii").strip()
    if not _HEX64_RE.match(text):
        raise ReleaseSignError(f"{path}: not a release key file (expected 64 lowercase hex chars)")
    return bytes.fromhex(text)


def public_key_hex(seed: bytes) -> str:
    return _ed.public_key_from_seed(seed).hex()


def keygen(key_id: str, key_dir: Path, *, allow_test: bool = False) -> tuple[Path, str]:
    if not _KEY_ID_RE.match(key_id):
        raise ReleaseSignError(f"key id {key_id!r}: use 3-64 chars of a-z, 0-9 and '-'")
    if key_id.startswith(TEST_KEY_PREFIX) and not allow_test:
        raise ReleaseSignError(f"key id {key_id!r} starts with {TEST_KEY_PREFIX!r}: reserved for test keys")
    key_dir.mkdir(parents=True, exist_ok=True)
    path = key_dir / f"{key_id}.key"
    if path.exists():
        raise ReleaseSignError(f"{path} already exists -- refusing to overwrite a release key")
    seed = os.urandom(32)
    # O_EXCL: never clobber, even in a race.
    fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="ascii", newline="\n") as fh:
        fh.write(seed.hex() + "\n")
    return path, public_key_hex(seed)


def check_trust(prod_keys: Mapping[str, str] | None) -> list[str]:
    """Problems that make a build NOT publishable (empty list = OK)."""
    problems: list[str] = []
    if prod_keys is None:
        return ["shared/release_keys.py (PROD_KEYS) is missing -- lane L3 adds it"]
    if not isinstance(prod_keys, Mapping) or not prod_keys:
        return ["PROD_KEYS is empty: the client would trust no key. Run `tools/release_sign.py keygen` "
                "(owner) and paste the public key into shared/release_keys.py"]
    for key_id, pub in prod_keys.items():
        if str(key_id).startswith(TEST_KEY_PREFIX):
            problems.append(f"PROD_KEYS trusts the test key {key_id!r}: a publishable build must not")
        if not _KEY_ID_RE.match(str(key_id)):
            problems.append(f"PROD_KEYS key id {key_id!r} is malformed")
        if not isinstance(pub, str) or not _HEX64_RE.match(pub):
            problems.append(f"PROD_KEYS[{key_id!r}] is not 64 lowercase hex chars")
    return problems


def load_release_keys() -> tuple[dict[str, str] | None, dict[str, str]]:
    try:
        from shared import release_keys as rk  # type: ignore[attr-defined]
    except ImportError:
        return None, {}
    return dict(getattr(rk, "PROD_KEYS", {}) or {}), dict(getattr(rk, "TEST_KEYS", {}) or {})


# ------------------------------------------------------------------ manifest


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def utc_now_stamp() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def build_manifest(
    *,
    target: str,
    channel: str,
    version: str,
    installer_name: str,
    installer_sha256: str,
    installer_size: int,
    issued_at: str,
    rollback_from: str | None = None,
    platform: str = PLATFORM,
) -> dict[str, Any]:
    if target not in TARGETS:
        raise ReleaseSignError(f"target {target!r}: expected one of {TARGETS}")
    if platform != PLATFORM:
        raise ReleaseSignError(f"platform {platform!r}: expected {PLATFORM}")
    if channel not in CHANNELS:
        raise ReleaseSignError(f"channel {channel!r}: expected one of {CHANNELS}")
    if not _VERSION_RE.match(version or ""):
        raise ReleaseSignError(f"version {version!r} is not MAJOR.MINOR.PATCH[-pre]")
    if not _INSTALLER_NAME_RE.match(installer_name or ""):
        raise ReleaseSignError(f"installer name {installer_name!r}: ASCII letters, digits, . _ - and .exe only")
    if not _HEX64_RE.match(installer_sha256 or ""):
        raise ReleaseSignError("installer SHA-256 must be 64 lowercase hex chars")
    if not isinstance(installer_size, int) or isinstance(installer_size, bool) or installer_size <= 0:
        raise ReleaseSignError("installer size must be a positive integer")
    if not _ISSUED_AT_RE.match(issued_at or ""):
        raise ReleaseSignError(f"issuedAt {issued_at!r} must be YYYY-MM-DDTHH:MM:SSZ")
    if rollback_from is not None:
        if not _VERSION_RE.match(rollback_from):
            raise ReleaseSignError(f"rollbackFrom {rollback_from!r} is not MAJOR.MINOR.PATCH[-pre]")
        if rollback_from == version:
            raise ReleaseSignError("a rollback manifest must name a different (bad) version")
    return {
        "allowDowngrade": rollback_from is not None,
        "channel": channel,
        "installerName": installer_name,
        "installerSha256": installer_sha256,
        "installerSize": installer_size,
        "issuedAt": issued_at,
        "platform": platform,
        "rollbackFrom": rollback_from,
        "schema": MANIFEST_SCHEMA,
        "target": target,
        "version": version,
    }


def canonical_manifest(manifest: Mapping[str, Any]) -> str:
    """The exact signed string (design 5.2). Non-ASCII is REFUSED, not escaped: prod columns
    are latin1 and would mangle it (the build must never produce such a manifest)."""
    for key, value in manifest.items():
        if not str(key).isascii() or (isinstance(value, str) and not value.isascii()):
            raise ReleaseSignError(f"manifest field {key!r} is not ASCII: refused (design 5.2)")
    return json.dumps(dict(manifest), sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def sign_manifest(manifest_str: str, seed: bytes) -> str:
    return _ed.sign(seed, manifest_str.encode("ascii")).hex()


def verify_manifest(manifest_str: str, signature_hex: str, public_hex: str) -> bool:
    if not _HEX128_RE.match(signature_hex or "") or not _HEX64_RE.match(public_hex or ""):
        return False
    try:
        data = manifest_str.encode("ascii")
    except UnicodeEncodeError:
        return False
    return bool(_ed.verify(bytes.fromhex(public_hex), data, bytes.fromhex(signature_hex)))


# ------------------------------------------------------------------ release file


def make_release_file(
    *,
    installer: Path,
    target: str,
    channel: str,
    version: str,
    key_id: str,
    seed: bytes,
    trusted_keys: Mapping[str, str],
    installer_url: str | None = None,
    github_repo: str = DEFAULT_GITHUB_REPO,
    release_notes: str = "",
    codename: str = "",
    rollback_from: str | None = None,
    build_commit: str = "",
    tests_skipped: bool = False,
    publishable: bool = False,
    payload_version: Mapping[str, Any] | None = None,
    issued_at: str | None = None,
) -> dict[str, Any]:
    installer = Path(installer)
    if not installer.is_file():
        raise ReleaseSignError(f"installer not found: {installer}")
    if not _KEY_ID_RE.match(key_id or ""):
        raise ReleaseSignError(f"key id {key_id!r} is malformed")

    derived = public_key_hex(seed)
    trusted = trusted_keys.get(key_id)
    if trusted is None:
        raise ReleaseSignError(f"key {key_id!r} is not in the trusted key list: the client would refuse "
                               "this release")
    if trusted != derived:
        raise ReleaseSignError(f"the private key file for {key_id!r} does not match the trusted public key "
                               f"(file -> {derived[:16]}..., trusted -> {str(trusted)[:16]}...)")
    if publishable:
        # The payload's own version.json (written by build_release.ps1) must agree: a payload
        # built with -E2ETestKeys trusts only the test key -- shipped, those PCs could never
        # verify another release (review #6). "Publishable" is never a default.
        if payload_version is None:
            raise ReleaseSignError("a publishable release needs the payload's version.json (--payload-version-json)")
        if payload_version.get("publishable") is not True or payload_version.get("e2eTestKeys"):
            raise ReleaseSignError("the payload was built as a test / non-publishable build (its version.json says so)")
        if key_id.startswith(TEST_KEY_PREFIX):
            raise ReleaseSignError("a publishable release cannot be signed with a test key")
        if tests_skipped:
            raise ReleaseSignError("a publishable release cannot skip the test suite")
        if not build_commit or not re.match(r"^[0-9a-f]{40}$", build_commit):
            raise ReleaseSignError("a publishable release needs the full 40-hex build commit")

    tag = release_tag(target, channel, version)
    url = installer_url or github_asset_url(github_repo, tag, installer.name)
    if publishable and not url.startswith("https://"):
        raise ReleaseSignError(f"installer URL must be https for a publishable release: {url}")
    if not (url.startswith("https://") or url.startswith("http://127.0.0.1") or url.startswith("http://localhost")):
        raise ReleaseSignError(f"installer URL must be https (or local http for a test build): {url}")

    manifest = build_manifest(
        target=target, channel=channel, version=version, installer_name=installer.name,
        installer_sha256=sha256_file(installer), installer_size=installer.stat().st_size,
        issued_at=issued_at or utc_now_stamp(), rollback_from=rollback_from,
    )
    manifest_str = canonical_manifest(manifest)
    signature = sign_manifest(manifest_str, seed)
    if not verify_manifest(manifest_str, signature, derived):
        raise ReleaseSignError("self-check failed: the signature does not verify")

    return {
        # Section 5.3 fields (the dashboard import reads these) ...
        "signedManifest": manifest_str,
        "signature": signature,
        "keyId": key_id,
        "installerUrl": url,
        "releaseNotes": release_notes,
        "codename": codename,
        # ... and provenance for publish_github_release.ps1 / the owner. Not signed.
        "githubRepo": github_repo,
        "githubTag": tag,
        "buildCommit": build_commit,
        "testsSkipped": bool(tests_skipped),
        "publishable": bool(publishable),
        "signedWith": ED25519_SOURCE,
    }


def write_release_file(data: Mapping[str, Any], path: Path) -> None:
    text = json.dumps(dict(data), indent=2, ensure_ascii=True) + "\n"
    Path(path).write_text(text, encoding="ascii", newline="\n")


def verify_release_file(
    data: Mapping[str, Any], trusted_keys: Mapping[str, str], installer: Path | None = None
) -> dict[str, Any]:
    for field in ("signedManifest", "signature", "keyId"):
        if not isinstance(data.get(field), str):
            raise ReleaseSignError(f"release file: {field} missing")
    key_id = data["keyId"]
    pub = trusted_keys.get(key_id)
    if pub is None:
        raise ReleaseSignError(f"release file is signed with {key_id!r}, which is not trusted")
    if not verify_manifest(data["signedManifest"], data["signature"], pub):
        raise ReleaseSignError("SIGNATURE INVALID: the manifest was not signed by the trusted key")
    manifest = json.loads(data["signedManifest"])
    if canonical_manifest(manifest) != data["signedManifest"]:
        raise ReleaseSignError("the signed manifest is not in canonical form")
    if installer is not None:
        installer = Path(installer)
        if installer.name != manifest["installerName"]:
            raise ReleaseSignError(f"installer name {installer.name!r} != manifest {manifest['installerName']!r}")
        if installer.stat().st_size != manifest["installerSize"]:
            raise ReleaseSignError("installer size differs from the manifest")
        if sha256_file(installer) != manifest["installerSha256"]:
            raise ReleaseSignError("installer SHA-256 differs from the manifest")
    return manifest


# ------------------------------------------------------------------ CLI


def _default_key_file(key_id: str) -> Path:
    return TEST_KEY_FILE if key_id == TEST_KEY_ID else default_key_dir() / f"{key_id}.key"


def _trusted_for(args) -> dict[str, str]:
    prod, test = load_release_keys()
    keys = dict(prod or {})
    if getattr(args, "allow_test_keys", False):
        keys.update(test)
        # The fixture key is always usable by test builds, even before L3's TEST_KEYS exists.
        if TEST_KEY_FILE.exists():
            keys.setdefault(TEST_KEY_ID, public_key_hex(read_seed(TEST_KEY_FILE)))
    return keys


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="release_sign.py", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("keygen")
    g.add_argument("--key-id", required=True)
    g.add_argument("--dir", type=Path, default=None)
    g.add_argument("--test", action="store_true", help="allow a test- key id")

    sub.add_parser("check-trust")

    s = sub.add_parser("sign")
    s.add_argument("--installer", type=Path, required=True)
    s.add_argument("--target", required=True, choices=TARGETS)
    s.add_argument("--channel", required=True, choices=CHANNELS)
    s.add_argument("--version", required=True)
    s.add_argument("--key-id", required=True)
    s.add_argument("--key-file", type=Path, default=None)
    s.add_argument("--installer-url", default=None)
    s.add_argument("--github-repo", default=DEFAULT_GITHUB_REPO)
    s.add_argument("--notes-file", type=Path, default=None)
    s.add_argument("--codename", default="")
    s.add_argument("--rollback-from", default=None)
    s.add_argument("--build-commit", default="")
    s.add_argument("--tests-skipped", action="store_true")
    s.add_argument("--publishable", action="store_true",
                   help="only build_release.ps1 passes it; needs --payload-version-json")
    s.add_argument("--not-publishable", action="store_true", help="the default; kept for clarity")
    s.add_argument("--payload-version-json", type=Path, default=None)
    s.add_argument("--allow-test-keys", action="store_true")
    s.add_argument("--out", type=Path, default=None)

    v = sub.add_parser("verify")
    v.add_argument("--release-file", type=Path, required=True)
    v.add_argument("--installer", type=Path, default=None)
    v.add_argument("--allow-test-keys", action="store_true")
    v.add_argument("--require-publishable", action="store_true")

    c = sub.add_parser("check-key", help="the key file matches the trusted public key of --key-id")
    c.add_argument("--key-id", required=True)
    c.add_argument("--key-file", type=Path, default=None)
    c.add_argument("--allow-test-keys", action="store_true")

    sub.add_parser("prod-key-ids", help="print the PROD_KEYS key ids, one per line")

    k = sub.add_parser("public-key")
    k.add_argument("--key-file", type=Path, required=True)

    t = sub.add_parser("tag")
    t.add_argument("--target", required=True, choices=TARGETS)
    t.add_argument("--channel", required=True, choices=CHANNELS)
    t.add_argument("--version", required=True)

    args = ap.parse_args(argv)
    try:
        if args.cmd == "keygen":
            path, pub = keygen(args.key_id, args.dir or default_key_dir(), allow_test=args.test)
            print(f"Private key written to {path} (back it up; never commit or share it).")
            print(f"keyId     : {args.key_id}")
            print(f"publicKey : {pub}")
            print("Paste into shared/release_keys.py PROD_KEYS and the backend prod config "
                  f"(monclub.release-signing.public-keys): \"{args.key_id}\": \"{pub}\"")
            return 0

        if args.cmd == "check-trust":
            prod, _test = load_release_keys()
            problems = check_trust(prod)
            for p in problems:
                print(f"NOT PUBLISHABLE: {p}", file=sys.stderr)
            if not problems:
                print(f"trusted release keys OK: {', '.join(sorted(prod or {}))}")
            return 1 if problems else 0

        if args.cmd == "sign":
            key_file = args.key_file or _default_key_file(args.key_id)
            notes = args.notes_file.read_text(encoding="utf-8") if args.notes_file else ""
            data = make_release_file(
                installer=args.installer, target=args.target, channel=args.channel, version=args.version,
                key_id=args.key_id, seed=read_seed(key_file), trusted_keys=_trusted_for(args),
                installer_url=args.installer_url, github_repo=args.github_repo, release_notes=notes,
                codename=args.codename, rollback_from=args.rollback_from, build_commit=args.build_commit,
                tests_skipped=args.tests_skipped,
                publishable=bool(args.publishable) and not args.not_publishable,
                payload_version=(json.loads(args.payload_version_json.read_text(encoding="utf-8-sig"))
                                 if args.payload_version_json else None),
            )
            out = args.out or args.installer.parent / release_file_name(
                args.target, args.version, rollback_from=args.rollback_from)
            write_release_file(data, out)
            print(f"release file: {out}")
            print(f"manifest    : {data['signedManifest']}")
            return 0

        if args.cmd == "verify":
            data = json.loads(args.release_file.read_text(encoding="utf-8"))
            if args.require_publishable and data.get("publishable") is not True:
                raise ReleaseSignError("this release file is marked NOT publishable (test / E2E build)")
            manifest = verify_release_file(data, _trusted_for(args), args.installer)
            print(f"OK: {manifest['target']} {manifest['version']} signed by {data['keyId']}")
            return 0

        if args.cmd == "check-key":
            key_file = args.key_file or _default_key_file(args.key_id)
            if not Path(key_file).exists():
                raise ReleaseSignError(f"private key file not found: {key_file}")
            derived = public_key_hex(read_seed(key_file))
            trusted = _trusted_for(args).get(args.key_id)
            if trusted is None:
                raise ReleaseSignError(f"key {args.key_id!r} is not trusted by this build")
            if trusted != derived:
                raise ReleaseSignError(f"{key_file} does not match the trusted public key of {args.key_id!r}")
            print(f"signing key {args.key_id} OK ({key_file})")
            return 0

        if args.cmd == "prod-key-ids":
            prod, _test = load_release_keys()
            for key_id in sorted(prod or {}):
                print(key_id)
            return 0

        if args.cmd == "public-key":
            print(public_key_hex(read_seed(args.key_file)))
            return 0

        if args.cmd == "tag":
            print(release_tag(args.target, args.channel, args.version))
            return 0
    except ReleaseSignError as exc:
        print(f"REFUSED: {exc}", file=sys.stderr)
        return 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
